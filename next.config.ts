import type { NextConfig } from "next";

const SECURITY_HEADERS = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
];

// Painel e APIs nunca entram no Google nem ficam em cache
const PRIVATE_HEADERS = [
  { key: "X-Robots-Tag", value: "noindex, nofollow" },
  { key: "Cache-Control", value: "no-store" },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [
      { source: "/:path*", headers: SECURITY_HEADERS },
      { source: "/dashboard", headers: PRIVATE_HEADERS },
      { source: "/dashboard/:path*", headers: PRIVATE_HEADERS },
      { source: "/api/:path*", headers: PRIVATE_HEADERS },
    ];
  },
  // Painel estático em public/dashboard (login por senha; dados via /api/dashboard, /api/ga4, /api/google-ads)
  async rewrites() {
    return [{ source: "/dashboard", destination: "/dashboard/index.html" }];
  },
  cacheComponents: true,
  partialPrefetching: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
